/**
 * Generates a real Semaphore v4 Groth16 proof for the ZeroDrop contracts and writes
 * contracts/test/fixtures/semaphore-proof.json. Run with: pnpm contracts:fixture
 *
 * The fixture is deterministic in its inputs (fixed identities, case, CID, group id 1).
 * Proving downloads the Semaphore depth wasm/zkey on first run through @zk-kit/artifacts
 * (https://snark-artifacts.pse.dev, cached under the OS temp dir). This is a dev-only step,
 * not app code, and the output JSON is committed so tests do not need the network.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { keccak256, toHex, type Hex } from "viem";
import { Identity } from "@semaphore-protocol/identity";
import { Group } from "@semaphore-protocol/group";
import { generateProof, verifyProof } from "@semaphore-protocol/proof";
import {
  encodeProofPoints,
  messageOf,
  scopeOf,
  toHexUint,
} from "./lib/zerodrop-hash.ts";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, "../contracts/test/fixtures/semaphore-proof.json");

/** Group id the fixture is bound to. Tests and check-local create the group first, so it is 1. */
const GROUP_ID = 1n;
const MEMBER_COUNT = 4;

const caseId = keccak256(toHex("zerodrop-fixture-case-1"));
const cidDigest = keccak256(toHex("zerodrop-fixture-document-1"));

async function main(): Promise<void> {
  const identities = Array.from({ length: MEMBER_COUNT }, (_, i) =>
    new Identity(`zerodrop-fixture-member-${i + 1}`),
  );
  const prover = identities[1];
  const commitments = identities.map((id) => id.commitment);
  const group = new Group(commitments);

  const message = messageOf(cidDigest as Hex, GROUP_ID, caseId);
  const scope = scopeOf(caseId);

  const proof = await generateProof(prover, group, message, scope);

  const ok = await verifyProof(proof);
  if (!ok) throw new Error("local verifyProof rejected the generated proof");

  if (BigInt(proof.message) !== message) throw new Error("message mismatch");
  if (BigInt(proof.scope) !== scope) throw new Error("scope mismatch");

  const points = proof.points.map((p) => BigInt(p));
  const fixture = {
    description:
      "Semaphore v4 Groth16 proof for ZeroDrop.record. Generated by scripts/make-fixture.ts. Do not edit by hand.",
    groupId: toHexUint(GROUP_ID),
    caseId,
    cidDigest,
    memberCount: MEMBER_COUNT,
    commitments: commitments.map((c) => toHexUint(c)),
    identityCommitment: toHexUint(prover.commitment),
    root: toHexUint(proof.merkleTreeRoot),
    nullifier: toHexUint(proof.nullifier),
    message: toHexUint(message),
    scope: toHexUint(scope),
    depth: proof.merkleTreeDepth,
    points: points.map((p) => toHexUint(p)),
    proof: encodeProofPoints(points),
  };

  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, JSON.stringify(fixture, null, 2) + "\n");
  console.log(`wrote ${OUT}`);
  console.log(`root=${fixture.root} depth=${fixture.depth} nullifier=${fixture.nullifier}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
