/**
 * Writes packages/core/src/abi.ts from the forge artifacts in contracts/out.
 * Run `forge build` first. Run with: pnpm abi:export
 *
 * Exports ABI objects only. messageOf, scopeOf and SNARK_SCALAR_FIELD live in the proof module.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function abiOf(name: string): unknown[] {
  const path = resolve(root, `contracts/out/${name}.sol/${name}.json`);
  const artifact = JSON.parse(readFileSync(path, "utf8")) as { abi: unknown[] };
  return artifact.abi;
}

const zeroDrop = JSON.stringify(abiOf("ZeroDrop"), null, 2);
const adapter = JSON.stringify(abiOf("SemaphoreVerifierAdapter"), null, 2);

const source = `// GENERATED by scripts/export-abi.ts from contracts/out. Do not edit by hand.

export const zeroDropAbi = ${zeroDrop} as const;

export const semaphoreVerifierAdapterAbi = ${adapter} as const;
`;

const out = resolve(root, "packages/core/src/abi.ts");
writeFileSync(out, source);
console.log(`wrote ${out}`);
